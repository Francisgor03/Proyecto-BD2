CREATE TABLE propietario (
  id_propietario   NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  nombres          VARCHAR2(80)  NOT NULL,
  apellidos        VARCHAR2(80)  NOT NULL,
  tipo_documento   VARCHAR2(3)   NOT NULL,
  numero_documento VARCHAR2(12)  NOT NULL,
  telefono         VARCHAR2(15),
  correo           VARCHAR2(100),
  fecha_registro   DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_propietario PRIMARY KEY (id_propietario),
  CONSTRAINT uq_propietario_doc UNIQUE (numero_documento),
  CONSTRAINT uq_propietario_correo UNIQUE (correo),
  CONSTRAINT ck_propietario_tipodoc CHECK (tipo_documento IN ('DNI','CE')),
  CONSTRAINT ck_propietario_correo CHECK (correo IS NULL OR correo LIKE '%@%')
);

CREATE TABLE parcela (
  id_parcela     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  id_propietario NUMBER(10)   NOT NULL,
  nombre         VARCHAR2(80) NOT NULL,
  area_hectareas NUMBER(8,2)  NOT NULL,
  ubicacion      VARCHAR2(150) NOT NULL,
  latitud        NUMBER(9,6),
  longitud       NUMBER(9,6),
  tipo_suelo     VARCHAR2(20) NOT NULL,
  CONSTRAINT pk_parcela PRIMARY KEY (id_parcela),
  CONSTRAINT fk_parcela_propietario FOREIGN KEY (id_propietario) REFERENCES propietario (id_propietario),
  CONSTRAINT uq_parcela_nombre UNIQUE (id_propietario, nombre),
  CONSTRAINT ck_parcela_area CHECK (area_hectareas > 0),
  CONSTRAINT ck_parcela_lat CHECK (latitud BETWEEN -90 AND 90),
  CONSTRAINT ck_parcela_lon CHECK (longitud BETWEEN -180 AND 180),
  CONSTRAINT ck_parcela_suelo CHECK (tipo_suelo IN ('ARENOSO','LIMOSO','ARCILLOSO','FRANCO','FRANCO_ARENOSO','FRANCO_ARCILLOSO'))
);

CREATE TABLE tipo_cultivo (
  id_tipo_cultivo NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  nombre          VARCHAR2(60)  NOT NULL,
  categoria       VARCHAR2(20)  NOT NULL,
  descripcion     VARCHAR2(200),
  duracion_dias   NUMBER(4)     NOT NULL,
  CONSTRAINT pk_tipo_cultivo PRIMARY KEY (id_tipo_cultivo),
  CONSTRAINT uq_tipo_cultivo_nombre UNIQUE (nombre),
  CONSTRAINT ck_tipo_cultivo_cat CHECK (categoria IN ('FRUTAL','HORTALIZA','CEREAL','LEGUMINOSA','TUBERCULO','INDUSTRIAL')),
  CONSTRAINT ck_tipo_cultivo_dur CHECK (duracion_dias > 0)
);

CREATE TABLE campania (
  id_campania     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  id_parcela      NUMBER(10)   NOT NULL,
  id_tipo_cultivo NUMBER(10)   NOT NULL,
  nombre          VARCHAR2(80) NOT NULL,
  fecha_inicio    DATE         NOT NULL,
  fecha_fin       DATE,
  estado          VARCHAR2(12) DEFAULT 'PLANIFICADA' NOT NULL,
  CONSTRAINT pk_campania PRIMARY KEY (id_campania),
  CONSTRAINT fk_campania_parcela FOREIGN KEY (id_parcela) REFERENCES parcela (id_parcela),
  CONSTRAINT fk_campania_cultivo FOREIGN KEY (id_tipo_cultivo) REFERENCES tipo_cultivo (id_tipo_cultivo),
  CONSTRAINT uq_campania_nombre UNIQUE (id_parcela, nombre),
  CONSTRAINT ck_campania_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio),
  CONSTRAINT ck_campania_estado CHECK (estado IN ('PLANIFICADA','EN_CURSO','FINALIZADA','CANCELADA'))
);

CREATE TABLE trabajador (
  id_trabajador    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  nombres          VARCHAR2(80) NOT NULL,
  apellidos        VARCHAR2(80) NOT NULL,
  numero_documento VARCHAR2(12) NOT NULL,
  cargo            VARCHAR2(20) NOT NULL,
  telefono         VARCHAR2(15),
  fecha_ingreso    DATE NOT NULL,
  estado           VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
  CONSTRAINT pk_trabajador PRIMARY KEY (id_trabajador),
  CONSTRAINT uq_trabajador_doc UNIQUE (numero_documento),
  CONSTRAINT ck_trabajador_cargo CHECK (cargo IN ('AGRICULTOR','TECNICO_CAMPO','SUPERVISOR','OPERADOR','ASISTENTE')),
  CONSTRAINT ck_trabajador_estado CHECK (estado IN ('ACTIVO','INACTIVO'))
);

CREATE TABLE asignacion_trabajador (
  id_asignacion    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  id_campania      NUMBER(10)    NOT NULL,
  id_trabajador    NUMBER(10)    NOT NULL,
  fecha_asignacion DATE          NOT NULL,
  actividad        VARCHAR2(100) NOT NULL,
  CONSTRAINT pk_asignacion PRIMARY KEY (id_asignacion),
  CONSTRAINT fk_asignacion_campania FOREIGN KEY (id_campania) REFERENCES campania (id_campania),
  CONSTRAINT fk_asignacion_trabajador FOREIGN KEY (id_trabajador) REFERENCES trabajador (id_trabajador),
  CONSTRAINT uq_asignacion UNIQUE (id_campania, id_trabajador, fecha_asignacion)
);

CREATE TABLE insumo (
  id_insumo          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  nombre             VARCHAR2(80) NOT NULL,
  tipo               VARCHAR2(15) NOT NULL,
  unidad_medida      VARCHAR2(10) NOT NULL,
  precio_referencial NUMBER(10,2) NOT NULL,
  CONSTRAINT pk_insumo PRIMARY KEY (id_insumo),
  CONSTRAINT uq_insumo_nombre UNIQUE (nombre),
  CONSTRAINT ck_insumo_tipo CHECK (tipo IN ('FERTILIZANTE','PESTICIDA','HERBICIDA','FUNGICIDA','SEMILLA','ENMIENDA')),
  CONSTRAINT ck_insumo_unidad CHECK (unidad_medida IN ('KG','L','SACO','UNIDAD')),
  CONSTRAINT ck_insumo_precio CHECK (precio_referencial >= 0)
);

CREATE TABLE aplicacion_insumo (
  id_aplicacion    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  id_campania      NUMBER(10)   NOT NULL,
  id_insumo        NUMBER(10)   NOT NULL,
  cantidad         NUMBER(10,2) NOT NULL,
  costo_unitario   NUMBER(10,2) NOT NULL,
  fecha_aplicacion DATE         NOT NULL,
  CONSTRAINT pk_aplicacion PRIMARY KEY (id_aplicacion),
  CONSTRAINT fk_aplicacion_campania FOREIGN KEY (id_campania) REFERENCES campania (id_campania),
  CONSTRAINT fk_aplicacion_insumo FOREIGN KEY (id_insumo) REFERENCES insumo (id_insumo),
  CONSTRAINT ck_aplicacion_cant CHECK (cantidad > 0),
  CONSTRAINT ck_aplicacion_costo CHECK (costo_unitario >= 0)
);

CREATE TABLE costo_produccion (
  id_costo       NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  id_campania    NUMBER(10)    NOT NULL,
  concepto       VARCHAR2(20)  NOT NULL,
  descripcion    VARCHAR2(200),
  monto          NUMBER(12,2)  NOT NULL,
  fecha_registro DATE          NOT NULL,
  CONSTRAINT pk_costo PRIMARY KEY (id_costo),
  CONSTRAINT fk_costo_campania FOREIGN KEY (id_campania) REFERENCES campania (id_campania),
  CONSTRAINT ck_costo_concepto CHECK (concepto IN ('MANO_OBRA','RIEGO','MAQUINARIA','TRANSPORTE','ALQUILER','OTROS')),
  CONSTRAINT ck_costo_monto CHECK (monto > 0)
);

CREATE TABLE sensor (
  id_sensor          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  id_parcela         NUMBER(10)   NOT NULL,
  tipo_sensor        VARCHAR2(20) NOT NULL,
  codigo_dispositivo VARCHAR2(30) NOT NULL,
  fecha_instalacion  DATE         NOT NULL,
  estado             VARCHAR2(15) DEFAULT 'ACTIVO' NOT NULL,
  CONSTRAINT pk_sensor PRIMARY KEY (id_sensor),
  CONSTRAINT fk_sensor_parcela FOREIGN KEY (id_parcela) REFERENCES parcela (id_parcela),
  CONSTRAINT uq_sensor_codigo UNIQUE (codigo_dispositivo),
  CONSTRAINT ck_sensor_tipo CHECK (tipo_sensor IN ('HUMEDAD_SUELO','TEMPERATURA','MULTIPARAMETRO')),
  CONSTRAINT ck_sensor_estado CHECK (estado IN ('ACTIVO','INACTIVO','MANTENIMIENTO'))
);

-- Indices sobre llaves foraneas (Oracle no los crea automaticamente)
CREATE INDEX ix_campania_cultivo   ON campania (id_tipo_cultivo);
CREATE INDEX ix_asignacion_trab    ON asignacion_trabajador (id_trabajador);
CREATE INDEX ix_aplicacion_camp    ON aplicacion_insumo (id_campania);
CREATE INDEX ix_aplicacion_insumo  ON aplicacion_insumo (id_insumo);
CREATE INDEX ix_costo_campania     ON costo_produccion (id_campania);
CREATE INDEX ix_sensor_parcela     ON sensor (id_parcela);

-- Vista: costo total por campania (insumos + otros costos; los insumos NO se registran en COSTO_PRODUCCION)
CREATE OR REPLACE VIEW v_costo_campania AS
SELECT c.id_campania, c.nombre AS campania, c.estado,
       NVL(ci.costo_insumos, 0) AS costo_insumos,
       NVL(cp.costo_otros, 0)   AS costo_otros,
       NVL(ci.costo_insumos, 0) + NVL(cp.costo_otros, 0) AS costo_total
FROM campania c
LEFT JOIN (SELECT id_campania, SUM(cantidad * costo_unitario) AS costo_insumos
           FROM aplicacion_insumo GROUP BY id_campania) ci ON ci.id_campania = c.id_campania
LEFT JOIN (SELECT id_campania, SUM(monto) AS costo_otros
           FROM costo_produccion GROUP BY id_campania) cp ON cp.id_campania = c.id_campania;
